'use strict';

/**
 * Compositor-side window positioning для KWin (Plasma) — D-Bus scripting API.
 * Парный backend к compositor-position.js (Hyprland через `hyprctl eval`);
 * контракт тот же: CommonJS, никогда не бросает, чистые билдеры для юнит-тестов.
 *
 * Как работает:
 *   1. Скрипт позиционирования пишется в os.tmpdir()/anix-kwin-position-<pid>.js
 *      (стабильный путь, перезаписывается только при изменении содержимого);
 *   2. `gdbus call --session --dest org.kde.KWin --object-path /Scripting
 *      --method org.kde.kwin.Scripting.unloadScript <name>` — сброс прошлого
 *      скрипта с тем же именем (на первом вызове его ещё нет — ошибка ожидаема
 *      и игнорируется). Без unload повторные loadScript либо падают, либо
 *      копят дубликаты, а баннер перепозиционируется часто;
 *   3. `... --method org.kde.kwin.Scripting.loadScript <path> <name>` →
 *      `(int32 <id>,)` (если < 0 / не распарсили — warn, run не вызываем);
 *   4. `gdbus call ... --object-path /Scripting/Script<id>
 *      --method org.kde.kwin.Script.run`.
 *
 * ПРОВЕРЕНО НА ЖИВОЙ СЕССИИ: вложенный kwin_wayland 6.7.5 — весь dispatch-цепочка
 * (unload → load → `(int32 <id>,)` → /Scripting/Script<id> → run) и позиционирование
 * Electron-окна (312,320 → 100,100, размер сохранён). Там же выяснено: Qt НЕ в
 * скоупе kwin-скриптов (см. комментарий у frameGeometry). НЕ проверено: Plasma 5
 * ветка clientList и поведение на реальном масштабированном Plasma (см. ниже).
 *
 * КООРДИНАТЫ — КЛЮЧЕВОЕ ОТЛИЧИЕ ОТ sway/Hyprland (физические px): KWin
 * frameGeometry — ЛОГИЧЕСКИЕ пиксели (Qt/QRectF, device-independent), как DIP
 * у Electron. Поэтому scaleFactor НЕ применяется — DIP проходят насквозь.
 * Проверка на реальной Plasma с масштабом 150% (Settings → Display & Monitor):
 * показать баннер на известных DIP-координатах и сверить фактический
 * frameGeometry через `qdbus org.kde.KWin /KWin supportInformation` или
 * отладочный kwin-скрипт с print(w.frameGeometry). Если баннер встал в 1.5×
 * от ожидаемого — предположение неверно, умножать на scaleFactor здесь.
 *
 * Совпадение окна строго по pid + caption: у процесса есть главное окно, а
 * два dev-инстанса дают одинаковый caption, но разные pid. caption у KWin —
 * WM_NAME (+ суффикс про hostname/shortcut на X11); на Wayland это title из
 * xdg-shell, у баннера он константный. НЕ ПРОВЕРЕНО: суффикс caption на
 * живом Wayland-сеансе — при несовпадении добавить startsWith/endsWith.
 *
 * Безопасность: в скрипт попадают только Number-коэрцированные числа и title,
 * сериализованный JSON.stringify (экранирует кавычки/бэкслеши/управляющие) —
 * инъекция в kwin-скрипт невозможна даже при злонамеренном title.
 */

const { execFile } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const logger = require('../../logger');

const GDBUS_TIMEOUT_MS = 2000;
const GDBUS_DEST = 'org.kde.KWin';

let warnedError = '';

/**
 * Детект KDE-сессии по окружению. Sync/cheap, без D-Bus (он async).
 * Допущение: Plasma-сессия выставляет XDG_CURRENT_DESKTOP (значение может быть
 * colon-списком, ищем токен 'kde' без учёта регистра) либо KDE_FULL_SESSION.
 * Nested kwin_wayland вне KDE-сессии может оба не выставить → false negative —
 * приемлемо: вызывающий уже решил, что мы на wayland, и не в Hyprland.
 */
function isAvailable() {
  const desktop = String(process.env.XDG_CURRENT_DESKTOP || '').toLowerCase();
  const tokens = desktop.split(':').map((part) => part.trim());
  if (tokens.includes('kde')) return true;
  // KDE_FULL_SESSION ставится стартовым скриптом Plasma ("1"/"true"); пустое
  // значение (="") не считаем детектом.
  return String(process.env.KDE_FULL_SESSION || '').trim() !== '';
}

/**
 * JS-источник, который исполнит KWin (внутри композитора, QJSEngine).
 * Чистая функция — покрыта юнит-тестом.
 *
 * KWin 6: workspace.windowList(); Plasma 5: workspace.clientList() — fallback
 * внутри скрипта (дёшево: пара typeof-проверок). Ошибки внутри скрипта KWin
 * глотает молча, поэтому каждый шаг в try/catch — чтобы один упавший шаг не
 * убил позиционирование.
 *
 * frameGeometry включает декорации; у frameless-баннера совпадает с клиентской
 * геометрией Electron. Размер дублирует Electron setBounds — идемпотентно.
 */
function buildScript({ pid, title, x, y, width: _width, height: _height, scaleFactor: _scaleFactor } = {}) {
  // _scaleFactor осознанно не используется — см. docblock про логические пиксели.
  const n = (v) => Math.round(Number(v) || 0);
  const qPid = Math.max(0, n(pid));
  // JSON.stringify экранирует ", \, \n, \u2028 и т.д. — инъекция невозможна.
  const qTitle = JSON.stringify(String(title ?? ''));
  return [
    '// generated by anix — позиционирование окна баннера, не редактировать',
    '(function () {',
    "  'use strict';",
    `  var PID = ${qPid};`,
    `  var TITLE = ${qTitle};`,
    '  var windows = null;',
    '  try {',
    "    if (typeof workspace === 'undefined') return;",
    "    if (typeof workspace.windowList === 'function') windows = workspace.windowList(); // KWin 6",
    "    else if (typeof workspace.clientList === 'function') windows = workspace.clientList(); // Plasma 5",
    '  } catch (e) { return; }',
    '  if (!windows) return;',
    '  for (var i = 0; i < windows.length; i++) {',
    '    var w = windows[i];',
    '    if (!w || w.pid !== PID || w.caption !== TITLE) continue;',
    '    try { if (typeof w.tile !== "undefined") w.tile = null; } catch (e) {} // выкинуть из кастомного тайла',
    // Декорации/фокус — здесь же: applyBannerRule вызывается до маппинга окна,
    // когда его ещё нет в windowList; а move-скрипт идёт по факту нахождения окна.
    '    try { w.noBorder = true; } catch (e) {}',
    '    try { w.skipTaskbar = true; } catch (e) {}',
    '    try { w.skipPager = true; } catch (e) {}',
    '    try { w.keepAbove = true; } catch (e) {}',
    '    try { w.onAllDesktops = true; } catch (e) {}',
    // ПРОВЕРЕНО на живом kwin_wayland 6.7.5: Qt в области видимости скриптов НЕ определён
    // ("ReferenceError: Qt is not defined"), frameGeometry присваивается plain-объектом.
    // Бэкенд position-only: размер не трогаем (держит Electron setBounds).
    `    try { var g = w.frameGeometry; w.frameGeometry = { x: ${n(x)}, y: ${n(y)}, width: g.width, height: g.height }; } catch (e) {}`,
    '  }',
    '})();',
    '',
  ].join('\n');
}

/**
 * argv для execFile('gdbus', argv) — загрузка скрипта (шаг 3 из docblock).
 * Чистая функция — покрыта юнит-тестом. Путь скрипта — один argv-элемент
 * (никакого shell, пробелы в пути безопасны).
 */
function buildDispatchArgv(scriptPath, scriptName) {
  return [
    'call',
    '--session',
    '--dest', GDBUS_DEST,
    '--object-path', '/Scripting',
    '--method', 'org.kde.kwin.Scripting.loadScript',
    String(scriptPath),
    String(scriptName),
  ];
}

/** warn с дедупликацией по тексту (logger здесь no-op, но вызовы оставлены). */
function warnOnce(message) {
  if (warnedError === message) return;
  warnedError = message;
  logger.warn('notifications', message);
}

/** Один gdbus call; никогда не бросает. err при выходе не 0 / таймауте. */
function gdbus(argv, callback) {
  execFile('gdbus', argv, { timeout: GDBUS_TIMEOUT_MS }, (err, stdout, stderr) => {
    callback(err, stdout, stderr);
  });
}

/**
 * Цепочка unload → load → run. Ошибки: unload молча (скрипта может ещё не быть),
 * load/run — warnOnce. Формат ответа loadScript `(int32 <id>,)` парсим рыхло.
 * @param {string} scriptPath
 * @param {string} scriptName
 * @param {(err:Error|null)=>void} [cb]
 */
function dispatch(scriptPath, scriptName, cb) {
  const done = (e) => { if (typeof cb === 'function') cb(e || null); };
  const unloadArgv = [
    'call',
    '--session',
    '--dest', GDBUS_DEST,
    '--object-path', '/Scripting',
    '--method', 'org.kde.kwin.Scripting.unloadScript',
    scriptName,
  ];
  gdbus(unloadArgv, () => {
    gdbus(buildDispatchArgv(scriptPath, scriptName), (loadErr, stdout, stderr) => {
      const loadMessage = loadErr
        ? `kwin loadScript failed: ${loadErr.message}`
        : (String(stderr || '').trim() ? `kwin loadScript stderr: ${String(stderr).trim()}` : '');
      if (loadMessage) warnOnce(loadMessage);
      if (loadErr) { done(loadErr); return; }
      // Рыхлый парс: "(int32 7,)" → 7. ПРОВЕРЕНО на живом kwin_wayland 6.7.5.
      // Основной шаблон — явный int32; fallback — последнее число в ответе (голый
      // /-?\d+/ нельзя: он ловит "32" из слова "int32").
      const text = String(stdout || '');
      const int32 = /\(\s*int32\s+(-?\d+)/i.exec(text);
      const numbers = text.match(/-?\d+/g);
      const id = int32 ? Number(int32[1]) : (numbers ? Number(numbers[numbers.length - 1]) : Number.NaN);
      if (!Number.isInteger(id) || id < 0) {
        warnOnce(`kwin loadScript: no script id in gdbus output: ${String(stdout || '').trim()}`);
        done(new Error('kwin: no script id'));
        return;
      }
      gdbus([
        'call',
        '--session',
        '--dest', GDBUS_DEST,
        '--object-path', `/Scripting/Script${id}`,
        '--method', 'org.kde.kwin.Script.run',
      ], (runErr, _runStdout, runStderr) => {
        const runMessage = runErr
          ? `kwin Script.run failed: ${runErr.message}`
          : (String(runStderr || '').trim() ? `kwin Script.run stderr: ${String(runStderr).trim()}` : '');
        if (runMessage) warnOnce(runMessage);
        done(runErr || null);
      });
    });
  });
}

const writtenScripts = new Map(); // scriptName -> { path, content }

/**
 * Записывает скрипт во временный файл безопасно: путь непредсказуем (random
 * суффикс), флаг 'wx' отказывается следовать за симлинком/перезаписывать —
 * классическую атаку через предсказуемый файл в /tmp это закрывает. Контент
 * меняется каждый вызов (координаты), поэтому пишем всегда, файл на каждый
 * процесс свой (pid в имени). Кэш — по имени скрипта, чтобы move- и rule-скрипты
 * не выбивали друг друга. Возвращает фактический путь для loadScript.
 */
function ensureScriptFile(scriptName, pid, script) {
  const prev = writtenScripts.get(scriptName) || null;
  const write = (suffix) => {
    const scriptPath = path.join(os.tmpdir(), `anix-kwin-position-${pid}-${suffix}.js`);
    const fd = fs.openSync(scriptPath, 'wx', 0o600);
    try {
      fs.writeFileSync(fd, script);
    } catch (e) {
      fs.closeSync(fd);
      throw e;
    }
    fs.closeSync(fd);
    return scriptPath;
  };
  if (prev && prev.content === script) {
    // tmp-cleaner мог снести файл между вызовами — кэш валидируем доступом.
    try {
      fs.accessSync(prev.path);
      return prev.path;
    } catch { /* ENOENT и пр. — перезапишем */ }
  }
  if (prev) {
    // Старый файл сносим отложенно: его loadScript ещё может читаться в полёте.
    const oldPath = prev.path;
    const cleanup = setTimeout(() => fs.unlink(oldPath, () => {}), GDBUS_TIMEOUT_MS * 2);
    cleanup.unref?.();
  }
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const scriptPath = write(`${process.pid.toString(36)}${Math.random().toString(36).slice(2, 6)}`);
      writtenScripts.set(scriptName, { path: scriptPath, content: script });
      return scriptPath;
    } catch (e) {
      if ((e && e.code) !== 'EEXIST') throw e;
    }
  }
  // 5 коллизий подряд случайного суффикса — статистически невозможны; сдаться
  // честно (moveWindow поймает и warnOnce).
  throw new Error('kwin script tmp file: repeated EEXIST');
}

/**
 * JS-источник правила окна баннера: без рамки/декораций, не в таскбаре/пейджере,
 * поверх всех. KWin не даёт per-window отключение анимаций через scripting API,
 * поэтому гасим хотя бы рамку и фокус-поведение. Чистая функция — под тестом.
 */
function buildBannerRuleScript(title) {
  const qTitle = JSON.stringify(String(title ?? ''));
  return [
    '// generated by anix — правило окна баннера, не редактировать',
    '(function () {',
    "  'use strict';",
    `  var TITLE = ${qTitle};`,
    '  var windows = null;',
    '  try {',
    "    if (typeof workspace === 'undefined') return;",
    "    if (typeof workspace.windowList === 'function') windows = workspace.windowList();",
    "    else if (typeof workspace.clientList === 'function') windows = workspace.clientList();",
    '  } catch (e) { return; }',
    '  if (!windows) return;',
    '  for (var i = 0; i < windows.length; i++) {',
    '    var w = windows[i];',
    '    if (!w || w.caption !== TITLE) continue;',
    '    try { w.noBorder = true; } catch (e) {}',
    '    try { w.skipTaskbar = true; } catch (e) {}',
    '    try { w.skipPager = true; } catch (e) {}',
    '    try { w.keepAbove = true; } catch (e) {}',
    '    try { w.onAllDesktops = true; } catch (e) {}',
    '  }',
    '})();',
    '',
  ].join('\n');
}

/**
 * Позиционирует окно баннера через KWin scripting. Безопасно вызывать всегда:
 * вне KWin-сессии вызывающий сюда не заходит, ошибки D-Bus — warn один раз.
 *
 * ВАЖНО про `cb`: KWin scripting API не возвращает результат скрипта
 * (`Script.run` успешен, даже если окно не найдено), поэтому достоверно
 * подтвердить перемещение нельзя. Бэкенд помечен `confirmsPlacement: false`:
 * фасад для таких бэкендов делает пару повторов (на случай позднего маппинга) и
 * затем считает позицию выставленной. `cb(err)` здесь означает только сбой
 * диспетчеризации, не «окно не найдено».
 *
 * @param {{pid:number,title:string,x:number,y:number,scaleFactor?:number}} args
 * @param {(err:Error|null)=>void} [cb]
 * @returns {boolean} true, если скрипт записан и диспетчеризация запущена
 */
function moveWindow({ pid, title, x, y, scaleFactor } = {}, cb) {
  try {
    const p = Math.max(0, Math.round(Number(pid) || 0));
    const script = buildScript({ pid: p, title, x, y, scaleFactor });
    const scriptName = `anix-position-${p}`;
    const scriptPath = ensureScriptFile(scriptName, p, script);
    dispatch(scriptPath, scriptName, cb);
    return true;
  } catch (err) {
    const message = `kwin moveWindow failed: ${err && err.message}`;
    warnOnce(message);
    if (typeof cb === 'function') cb(err);
    return false;
  }
}

/**
 * Правило окна баннера: без рамки/декораций, не в таскбаре, поверх. Через
 * KWin scripting (frameGeometry-скрипт идёт тем же путём load/run).
 * @param {string} title
 * @param {(err:Error|null)=>void} [cb]
 */
function applyBannerRule(title, cb) {
  try {
    const script = buildBannerRuleScript(title);
    const scriptName = `anix-banner-rule-${process.pid}`;
    const scriptPath = ensureScriptFile(scriptName, process.pid, script);
    dispatch(scriptPath, scriptName, cb);
    return true;
  } catch (err) {
    const message = `kwin banner rule failed: ${err && err.message}`;
    warnOnce(message);
    if (typeof cb === 'function') cb(err);
    return false;
  }
}

